// Fails when the Solidity API reference documents something tnt-core no longer has.
//
// The reference pages under pages/developers/api/reference are generated from
// tnt-core by solidity-docgen. When an interface changes upstream and the docs
// are not regenerated, they keep describing functions that no longer exist, and
// nothing catches it: check-tnt-core-sync.mjs pins one interface by hand, and no
// other check reads these files at all. An audit found five interfaces
// documenting functions that are absent from tnt-core entirely.
//
// Deliberately conservative to stay false-positive free. A documented name only
// fails if it appears NOWHERE in tnt-core src/. That keeps inherited members,
// renamed files, and moved interfaces from tripping the build, while still
// catching a name that upstream deleted or never had.

import { readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const REFERENCE_DIR = path.join(repoRoot, "pages/developers/api/reference");

function resolveTntCoreDir() {
  const candidates = [
    process.env.TNT_CORE_DIR && path.resolve(process.env.TNT_CORE_DIR),
    path.resolve(repoRoot, "../tnt-core"),
    path.resolve(repoRoot, "../../tnt-core"),
  ].filter(Boolean);
  for (const candidate of candidates) {
    if (statSafe(path.join(candidate, "src"))) return candidate;
  }
  throw new Error(
    `Unable to locate tnt-core checkout. Tried: ${candidates.join(", ")}`,
  );
}

function statSafe(p) {
  try {
    return statSync(p);
  } catch {
    return null;
  }
}

function walk(dir, filter, out = []) {
  for (const entry of readdirSync(dir)) {
    const p = path.join(dir, entry);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, filter, out);
    else if (filter(p)) out.push(p);
  }
  return out;
}

// Every function and event name tnt-core actually declares.
const tntCoreDir = resolveTntCoreDir();
const declared = new Set();
for (const file of walk(path.join(tntCoreDir, "src"), (p) =>
  p.endsWith(".sol"),
)) {
  const src = readFileSync(file, "utf8");
  for (const m of src.matchAll(
    /\b(?:function|event|error)\s+([A-Za-z_]\w*)\s*\(/g,
  )) {
    declared.add(m[1]);
  }
}

// What the reference pages claim exists.
const findings = [];
for (const page of walk(REFERENCE_DIR, (p) => p.endsWith(".mdx"))) {
  const content = readFileSync(page, "utf8");
  const rel = path.relative(repoRoot, page);
  const documented = new Map(); // name -> first line number
  const lines = content.split("\n");
  lines.forEach((line, index) => {
    const m = line.match(/^\s*(?:function|event|error)\s+([A-Za-z_]\w*)\s*\(/);
    if (m && !documented.has(m[1])) documented.set(m[1], index + 1);
  });

  for (const [name, line] of documented) {
    if (!declared.has(name)) findings.push({ page: rel, line, name });
  }
}

if (findings.length > 0) {
  const pages = new Set(findings.map((f) => f.page));
  console.error(
    `${findings.length} documented member(s) across ${pages.size} page(s) do not exist in tnt-core.\n` +
      "These pages are generated by solidity-docgen. Regenerate them against tnt-core main\n" +
      "rather than editing them by hand.\n",
  );
  for (const { page, line, name } of findings)
    console.error(`${page}:${line} ${name}`);
  process.exit(1);
}

console.log(
  `Solidity reference check passed. Every documented member exists in tnt-core (${declared.size} declared).`,
);
